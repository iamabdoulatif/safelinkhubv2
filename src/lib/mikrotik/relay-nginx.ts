type RelayWebForward = {
  publicPort: number;
  targetPort: number;
  tunnelIp: string;
  relayHost: string;
};


const DOMAIN = /^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;


/* PERFORMANCE (21/11/2026) — lenteur des accès MikHmon / WebFig mesurée :
   - chaque requête ouvrait une NOUVELLE connexion TCP vers le routeur, à
     95–140 ms par le tunnel : un `upstream` avec `keepalive` (et l'en-tête
     Connection vidé) réutilise les connexions ;
   - côté navigateur, la liaison cliente perdait 5 % des paquets : HTTP/2 et le
     cache de session TLS évitent d'ouvrir (et de renégocier) une connexion par
     fichier, chacune exposée à un SYN perdu (1 s et plus). */
function relayForwardServer(forward: RelayWebForward): string {
  const upstream = `slh_fwd_${forward.publicPort}`;
  return (
    `upstream ${upstream} {\n` +
    `  server ${forward.tunnelIp}:${forward.targetPort};\n` +
    `  keepalive 8;\n` +
    `  keepalive_timeout 60s;\n` +
    `}\n` +
    `server {\n` +
    `  listen ${forward.publicPort} ssl http2;\n` +
    `  server_name ${forward.relayHost};\n` +
    `  ssl_certificate     /etc/nginx/certs/wildcard.crt;\n` +
    `  ssl_certificate_key /etc/nginx/certs/wildcard.key;\n` +
    `  error_page 497 =301 https://$host:$server_port$request_uri;\n` +
    `  error_page 502 503 504 =503 /offline-${forward.publicPort}.html;\n` +
    `  location = /offline-${forward.publicPort}.html {\n` +
    `    root /etc/nginx/slh-errors;\n` +
    `    internal;\n` +
    `  }\n` +
    `  location / {\n` +
    `    proxy_pass http://${upstream};\n` +
    `    proxy_set_header Host $host;\n` +
    `    proxy_http_version 1.1;\n` +
    `    proxy_set_header Connection "";\n` +
    `    proxy_intercept_errors on;\n` +
    `    proxy_connect_timeout 5s;\n` +
    `  }\n` +
    `}`
  );
}

/** Builds the nginx include consumed by the relay's existing sync script. */
export function buildRelayNginxConfig(input: { webForwards: RelayWebForward[] }): string {
  const seenPorts = new Set<number>();
  const forwards = input.webForwards
    .filter((forward) => {
      if (seenPorts.has(forward.publicPort)) return false;
      seenPorts.add(forward.publicPort);
      return true;
    })
    .map(relayForwardServer);
  /* Les instances MikHmon cloud ne sont PLUS servies ici : Traefik détient
     443 sur le relais et porte déjà le certificat joker. Émettre un
     `listen 443` faisait échouer `nginx -t`, donc refuser le rechargement du
     fichier ENTIER — toutes les redirections gelaient avec lui. */
  // Cache de session TLS partagé par tous les vhosts (contexte http).
  const tls = `ssl_session_cache shared:SLH_FWD_SSL:10m;\nssl_session_timeout 4h;\n`;
  return `# Auto-generated by SafeLinkHub (relay-nginx). Do not edit.\n${tls}${forwards.join("\n")}\n`;
}
